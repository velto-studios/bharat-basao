// Builds src/data/map.ts: one merged outline of the subcontinent, city points and rivers.
// Run: node scripts/build-map.cjs  (needs devDependencies world-atlas, topojson-client, topojson-simplify, d3-geo)
const t=require('world-atlas/countries-50m.json');
const topo=require('topojson-client'), simp=require('topojson-simplify'), d3=require('d3-geo');
const ids=new Set(['356','586','050','524','064','144','104']);
let tt=simp.presimplify(t); tt=simp.simplify(tt, 0.0012);
const geoms=tt.objects.countries.geometries.filter(g=>ids.has(g.id));
const merged=topo.merge(tt,geoms);
const W=1000,H=1000;
const proj=d3.geoMercator().fitExtent([[30,30],[W-30,H-30]],merged);
const path=d3.geoPath(proj).digits(1);
let d=path(merged);
// drop tiny islands
const parts=d.split(/(?=M)/).filter(s=>{const n=s.split(/[LZ]/).length;return n>6});
d=parts.join('');
const cities=require('./cities.json').map(([n,la,lo])=>{const [x,y]=proj([lo,la]);return {name:n,x:+x.toFixed(1),y:+y.toFixed(1)}});
const rivers={
 ganga:[[30.98,78.93],[29.95,78.16],[27.3,79.9],[25.44,81.85],[25.32,82.97],[25.59,85.14],[25.25,87.0],[24.2,88.3],[23.0,89.6],[22.2,90.4]],
 indus:[[34.15,77.58],[35.3,75.5],[34.0,72.3],[32.5,71.5],[30.5,70.9],[27.7,68.85],[25.4,68.37],[24.3,67.6]],
 brahmaputra:[[27.9,95.2],[27.47,94.91],[26.6,93.0],[26.14,91.74],[25.9,89.8],[24.2,89.7],[23.0,89.6]],
 narmada:[[22.67,81.75],[23.18,79.99],[22.6,77.7],[22.2,75.5],[21.7,73.0]],
 godavari:[[19.99,73.79],[19.2,76.0],[18.9,79.0],[17.9,80.9],[16.8,81.9],[16.5,82.3]],
 kaveri:[[12.4,75.6],[12.3,76.8],[12.1,77.6],[11.2,78.4],[10.9,79.8]]};
const rv={};for(const k in rivers){const pts=rivers[k].map(([la,lo])=>proj([lo,la]).map(v=>+v.toFixed(1)));rv[k]=pts}
const out=`// Generated by scripts/build-map.cjs from Natural Earth 1:50m (public domain) via world-atlas.\n// Do not edit by hand.\nexport const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const LAND_PATH = ${JSON.stringify(d)};\nexport const CITIES: { name: string; x: number; y: number }[] = ${JSON.stringify(cities)};\nexport const RIVERS: Record<string, [number, number][]> = ${JSON.stringify(rv)};\nexport const NAGPUR = ${JSON.stringify(cities.find(c=>c.name==='Nagpur'))};\n`;
require('fs').writeFileSync(require('path').join(__dirname,'../src/data/map.ts'),out);
console.log(d.length, parts.length, cities.length);
